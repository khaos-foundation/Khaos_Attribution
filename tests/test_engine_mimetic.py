def test_check_reports_a_missing_checkout_and_changes_nothing(tmp_path, monkeypatch):
    calls = []
    monkeypatch.setattr(P, "_run", lambda cmd, cwd=None, env=None: calls.append(cmd) or _done())
    monkeypatch.setattr(P, "git_usable", lambda: True)
    report = P.provision(tmp_path / "mimetic-a0", device="mps", check_only=True)
    assert not report.passed and "not present" in report.text()
    assert calls == [] and not (tmp_path / "mimetic-a0").exists()


def test_check_wants_each_weight_set_at_its_pinned_revision(tmp_path, monkeypatch):
    root = tmp_path / "mimetic-a0"
    (root / ".git").mkdir(parents=True)
    (root / ".venv" / "bin").mkdir(parents=True)
    (root / ".venv" / "bin" / "python").write_text("")

    def fake_run(cmd, cwd=None, env=None):
        cmd = [str(c) for c in cmd]
        if "rev-parse" in cmd:
            return _done(out=DESCRIPTOR.commit + "\n")
        return _done(0, "ok")
    monkeypatch.setattr(P, "_run", fake_run)
    monkeypatch.setattr(P, "git_usable", lambda: True)
    monkeypatch.setattr(P, "contract_present", lambda python: True)
    asked = []
    have = set()
    monkeypatch.setattr(P, "cached", lambda repo, files, rev: asked.append((repo, rev)) or repo in have)
    monkeypatch.setattr(P, "pin_ref", lambda repo, rev, check_only=False: (True, ""))
    report = P.provision(root, device="mps", check_only=True)
    assert "at the pin" in report.text() and "t5-base missing" in report.text() and not report.passed
    assert {rev for _, rev in asked} == {w["revision"] for w in DESCRIPTOR.weights}
    have.update(w["repo"] for w in DESCRIPTOR.weights)
    assert P.provision(root, device="mps", check_only=True).passed


def test_the_measure_runs_at_float32_and_refuses_a_device_never_measured():
    assert M.expected_dtype("cuda") == M.expected_dtype("mps") == "fp32"
    assert M.memory_plan("mps", 16, total_gb=32)["fits"] == "resident"
    small = M.memory_plan("mps", 16, total_gb=16)
    assert small["fits"] is None and "needs about" in small["refusal"]
    cuda = M.memory_plan("cuda", 16, total_gb=96)
    assert cuda["fits"] is None and "not been measured on cuda" in cuda["refusal"]
    with pytest.raises(NotImplementedError):
        M.scorer_need_gb(16, device_type="cuda")


def test_epochs_become_steps_and_the_command_carries_the_recipe(tmp_path):
    steps = T.steps_for({"max_epochs": 10, "batch_size": 2, "checkpoint_every_n_epochs": 5}, n_pairs=7)
    assert steps == {"per_epoch": 4, "total": 40, "checkpoint_every": 20, "epochs": 10}
    api = T.TrainingApi(root=tmp_path, runtime="torch", python=tmp_path / "python")
    cmd = T.trainer_command(api, {"adapter_rank": 8, "adapter_alpha": 16, "adapter_type": "lokr", "learning_rate": 2e-4,
                                  "batch_size": 2}, tensor_dir=tmp_path / "clips", save_dir=tmp_path / "out", steps=steps,
                            seed=3, device="mps")
    flags = dict(zip(cmd[2::2], cmd[3::2]))
    assert flags["--steps"] == "40" and flags["--checkpoint-every"] == "20" and flags["--rank"] == "8"
    assert flags["--adapter-type"] == DESCRIPTOR.adapter["type"], "a type stable-audio-tools lacks falls back to the descriptor's"
    assert flags["--lr"] == "0.0002" and flags["--seed"] == "3"


def test_losses_and_checkpoints_are_read_from_what_the_driver_writes(tmp_path):
    (tmp_path / T.LOSSES_CSV).write_text("step,loss\n0,1.09\n1,1.02\n2,\n", encoding="utf-8")
    assert T.losses_from_csv(tmp_path) == [(0, 1.09), (1, 1.02)]
    assert T.losses_from_csv(tmp_path / "none") == []
    assert T.checkpoint_step(tmp_path / "epoch=0-step=120.ckpt") == 120 and T.checkpoint_step(tmp_path / "last.ckpt") is None


def test_a_session_refuses_a_resume_and_too_few_pairs(tmp_path):
    api = T.TrainingApi(root=tmp_path, runtime="torch", python=tmp_path / "python")
    clips = tmp_path / "clips"
    clips.mkdir()
    (clips / "a.wav").write_bytes(b"")
    kw = dict(checkpoint_root=tmp_path, tensor_dir=clips, output_dir=tmp_path / "out", device="mps", precision="32", seed=1)
    with pytest.raises(TrainingUnavailable, match="do not resume"):
        T.open_session(api, {}, resume_from=tmp_path, **kw)
    with pytest.raises(TrainingUnavailable, match="at least 2 pairs"):
        T.open_session(api, {}, **kw)


