def _done(code=0, out="", err=""):
    return subprocess.CompletedProcess(args=[], returncode=code, stdout=out, stderr=err)


def test_mimetic_is_known_experimental_and_says_so_to_the_rooms():
    """The rooms read the experimental label and its note from capabilities, never from a constant of their own."""
    assert "mimetic-a0" in KNOWN_ENGINES and descriptor("mimetic-a0").status == "experimental"
    caps = capabilities("mimetic-a0")
    assert caps["status"] == "experimental" and caps["status_note"]
    assert caps["bounds"]["duration"] == [1, 16]
    assert capabilities("acestep-1.5")["status"] == "stable"


def test_the_descriptor_pins_code_and_every_weight_set():
    assert len(DESCRIPTOR.commit) == 40 and DESCRIPTOR.licence["name"] == "MIT License"
    for w in DESCRIPTOR.weights:
        assert len(w["revision"]) == 40 and set(w["components"]) <= set(w["patterns"])


def test_micks_lock_is_installed_without_his_torch_and_without_git():
    export = "\n".join([
        "# generated by uv", "numpy==1.26.4", "torch==2.7.1+cu126 ; sys_platform == 'linux'", "torchaudio==2.7.1",
        "torchvision==0.22.1", "nvidia-cudnn-cu12==9.5.1.17 ; sys_platform == 'linux'", "triton==3.3.1", "    # via x",
        "stable-audio-tools @ git+https://github.com/Stability-AI/stable-audio-tools@3241adba4fc2a85cf5b29d9eb68d42f40a28e820",
        "-e .",
    ])
    req = P.locked_requirements(export)
    assert "numpy==1.26.4" in req and "torch" not in req.replace("stable-audio-tools", "") and "nvidia" not in req
    assert "stable-audio-tools @ https://github.com/Stability-AI/stable-audio-tools/archive/3241adba4fc2a85cf5b29d9eb68d42f40a28e820.tar.gz" in req
    assert "git+" not in req and "-e" not in req


