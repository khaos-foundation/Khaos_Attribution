"""Write src/khaos_attribution/weights_pins.py: each model set's revision and per-file sha256, read from the Khaos
mirror's manifests and, with --verify-hub, checked file by file against the hub (anonymously) first.

    python scripts/pin_weights.py [--mirror URL] [--verify-hub] [--write]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "khaos_attribution" / "weights_pins.py"
MIRROR = "https://weights.khaos.dev"
HUB = "https://huggingface.co"
REPOS = (
    "stabilityai/stable-audio-3-medium-base", "stabilityai/stable-audio-3-optimized",
    "mlx-community/whisper-large-v2-mlx", "Systran/faster-whisper-large-v2", "facebook/audioseal",
    "ACE-Step/Ace-Step1.5", "ACE-Step/acestep-v15-base", "lukewys/laion_clap", "roberta-base", "bert-base-uncased",
    "facebook/bart-base", "ggml-org/Qwen2.5-Omni-7B-GGUF", "Qwen/Qwen3-8B-GGUF", "OpenMOSS-Team/MOSS-Music-8B-Instruct",
    "micknoisemachine/mimetic-a0", "t5-base",
)
HEADER = '''"""Every model set the rooms install, at one revision, with the sha256 of each file. Generated by
scripts/pin_weights.py; the hub and the Khaos mirror are both held to these, so neither is trusted for its own hashes."""

PINS: dict = '''


def _json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=60) as answer:  # no request header names this project to the hub
        return json.load(answer)


def render(pins: dict) -> str:
    """The module's text for `pins`: the same input always gives the same bytes."""
    return HEADER + _literal(pins) + "\n"


def _literal(pins: dict) -> str:
    out = ["{"]
    for repo in sorted(pins):
        out.append(f'    {repo!r}: {{"revision": {pins[repo]["revision"]!r}, "files": (')
        for f in pins[repo]["files"]:
            path, size, sha256 = (f["path"], f["size"], f["sha256"]) if isinstance(f, dict) else f
            out.append(f"        ({path!r}, {size}, {sha256!r}),")
        out.append("    )},")
    out.append("}")
    return "\n".join(out)


def from_mirror(mirror: str) -> dict:
    pins = {}
    for repo in REPOS:
        doc = _json(f"{mirror}/{repo}/manifest.json")
        pins[repo] = {"revision": doc["revision"],
                      "files": [{"path": f["path"], "size": int(f["size"]), "sha256": f["sha256"]} for f in doc["files"]]}
    return pins


def hub_differences(pins: dict) -> list:
    """Files the hub does not hold at the pinned revision, or holds with another size or sha256."""
    bad = []
    for repo, pin in pins.items():
        info = _json(f"{HUB}/api/models/{repo}/revision/{pin['revision']}?blobs=true")
        hub = {s["rfilename"]: s for s in info["siblings"]}
        for f in pin["files"]:
            s = hub.get(f["path"])
            if s is None or s.get("size") != f["size"]:
                bad.append((repo, f["path"], "missing or another size"))
                continue
            digest = (s.get("lfs") or {}).get("sha256")
            if digest is None:                       # a small file the hub keeps outside LFS: hash its bytes
                h = hashlib.sha256()
                with urllib.request.urlopen(f"{HUB}/{repo}/resolve/{pin['revision']}/{f['path']}", timeout=120) as body:
                    for chunk in iter(lambda: body.read(1 << 20), b""):
                        h.update(chunk)
                digest = h.hexdigest()
            if digest != f["sha256"]:
                bad.append((repo, f["path"], "another sha256"))
    return bad


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mirror", default=MIRROR)
    parser.add_argument("--verify-hub", action="store_true")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    if args.write and not args.verify_hub:
        parser.error("--write needs --verify-hub: a pin is the hub's hash, not the mirror's own word")
    try:
        pins = from_mirror(args.mirror.rstrip("/"))
        bad = hub_differences(pins) if args.verify_hub else []
    except (urllib.error.URLError, OSError, ValueError, KeyError) as exc:
        print(f"could not read the sets: {exc}", file=sys.stderr)
        return 2
    for repo, path, why in bad:
        print(f"{repo}: {path}: {why}", file=sys.stderr)
    if bad:
        return 1
    files = sum(len(p["files"]) for p in pins.values())
    print(f"{len(pins)} sets, {files} files" + (", every one equal to the hub's" if args.verify_hub else ""))
    if args.write:
        TARGET.write_text(render(pins), encoding="utf-8")
        print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
